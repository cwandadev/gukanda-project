// Run: bun scripts/gen-icons.mjs
// Copies the SVG paths of the Boxicons we use into src/components/iconPaths.ts.
import { readFileSync, writeFileSync } from 'node:fs';

// our icon name -> Boxicons 2.1.4 file (regular style)
// Boxicons has NO dedicated language/translate icon, so "language" uses the globe.
const ICONS = {
  home: 'bx-home',
  calendar: 'bx-calendar',
  calendarPlus: 'bx-calendar-plus',
  calendarCheck: 'bx-calendar-check',
  user: 'bx-user',
  group: 'bx-group',
  grid: 'bx-grid-alt',
  clipboard: 'bx-clipboard',
  cog: 'bx-cog',
  data: 'bx-data',
  clock: 'bx-time',
  document: 'bx-file',
  check: 'bx-check',
  checkCircle: 'bx-check-circle',
  close: 'bx-x',
  warning: 'bx-error',
  info: 'bx-info-circle',
  language: 'bx-globe',
  show: 'bx-show',
  hide: 'bx-hide',
  chevronLeft: 'bx-chevron-left',
  chevronRight: 'bx-chevron-right',
  chevronDown: 'bx-chevron-down',
  plus: 'bx-plus',
  minus: 'bx-minus',
  trash: 'bx-trash',
  envelope: 'bx-envelope',
  lock: 'bx-lock-alt',
  logout: 'bx-log-out',
};

const out = {};
const missing = [];

for (const [name, file] of Object.entries(ICONS)) {
  try {
    const svg = readFileSync(`node_modules/boxicons/svg/regular/${file}.svg`, 'utf8');
    const paths = [...svg.matchAll(/<path[^>]*?\sd="([^"]+)"/g)].map((m) => m[1]);
    if (paths.length === 0) throw new Error('no path found');
    out[name] = paths;
  } catch {
    missing.push(file);
  }
}

if (missing.length > 0) {
  console.error('Missing or unreadable icons:', missing.join(', '));
  process.exit(1);
}

writeFileSync(
  'src/components/iconPaths.ts',
  `// GENERATED by scripts/gen-icons.mjs from Boxicons 2.1.4. Do not edit by hand.\n` +
    `export const iconPaths = ${JSON.stringify(out, null, 2)} as const;\n` +
    `export type IconName = keyof typeof iconPaths;\n`,
);
console.log(`  generated src/components/iconPaths.ts (${Object.keys(out).length} icons)`);
